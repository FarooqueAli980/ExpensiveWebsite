import PDFDocument from 'pdfkit';
import ExcelJS from 'exceljs';
import { Parser } from 'json2csv';
import Transaction from '../models/Transaction.js';

const formatCurrency = (amount) => `$${Number(amount).toFixed(2)}`;

const buildQuery = ({ startDate, endDate, category, type, minAmount, maxAmount, reportType, keyword }, userId) => {
  const query = { user: userId };

  if (startDate) query.date = { ...query.date, $gte: new Date(startDate) };
  if (endDate) query.date = { ...query.date, $lte: new Date(endDate) };
  if (category) query.category = category;
  if (type) query.type = type;
  if (minAmount) query.amount = { ...query.amount, $gte: Number(minAmount) };
  if (maxAmount) query.amount = { ...query.amount, $lte: Number(maxAmount) };
  if (keyword) {
    query.$or = [
      { title: { $regex: keyword, $options: 'i' } },
      { note: { $regex: keyword, $options: 'i' } },
    ];
  }

  const now = new Date();
  switch (reportType) {
    case 'income':
      query.type = 'Income';
      break;
    case 'expense':
      query.type = 'Expense';
      break;
    case 'monthly':
      query.date = {
        ...query.date,
        $gte: new Date(now.getFullYear(), now.getMonth(), 1),
        $lte: new Date(now.getFullYear(), now.getMonth() + 1, 0, 23, 59, 59),
      };
      break;
    case 'yearly':
      query.date = {
        ...query.date,
        $gte: new Date(now.getFullYear(), 0, 1),
        $lte: new Date(now.getFullYear(), 11, 31, 23, 59, 59),
      };
      break;
    case 'all':
    default:
      break;
  }

  if (reportType === 'category' && category) {
    query.category = category;
  }

  return query;
};

const buildReportMeta = (userName, title) => ({
  generatedAt: new Date().toISOString(),
  reportTitle: title,
  generatedBy: userName,
});

const getAttachmentFilenameHeader = (reportMeta, ext) => {
  const filename = reportMeta.reportTitle.replace(/\s+/g, '_') + `.${ext}`;
  return 'attachment; filename="' + filename + '"';
};

const buildRows = (transactions) => transactions.map((transaction) => ({
  date: transaction.date.toISOString().split('T')[0],
  title: transaction.title,
  description: transaction.note || '',
  category: transaction.category?.name || 'Uncategorized',
  type: transaction.type,
  amount: Number(transaction.amount).toFixed(2),
  paymentMethod: transaction.paymentMethod || 'Unknown',
  notes: transaction.note || '',
}));

const buildSummary = (transactions) => {
  const totalIncome = transactions.filter((item) => item.type === 'Income').reduce((sum, item) => sum + Number(item.amount || 0), 0);
  const totalExpense = transactions.filter((item) => item.type === 'Expense').reduce((sum, item) => sum + Number(item.amount || 0), 0);
  return {
    totalIncome,
    totalExpense,
    netBalance: totalIncome - totalExpense,
  };
};

const populateTransactions = async (query) => Transaction.find(query).populate('category', 'name').sort({ date: -1 });

export const exportPdfReport = async (req, res) => {
  try {
    const { reportType, title } = req.query;
    const query = buildQuery(req.query, req.user._id);
    const transactions = await populateTransactions(query);
    const summary = buildSummary(transactions);
    const reportMeta = buildReportMeta(req.user.name, title || 'Expense Report');

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', getAttachmentFilenameHeader(reportMeta, 'pdf'));

    const doc = new PDFDocument({ margin: 40, size: 'A4' });
    doc.pipe(res);
    doc.fontSize(20).text(reportMeta.reportTitle, { align: 'center' });
    doc.moveDown(0.25);
    doc.fontSize(10).fillColor('#6b7280').text(`Generated by: ${reportMeta.generatedBy}`, { align: 'left' });
    doc.text(`Generated at: ${new Date(reportMeta.generatedAt).toLocaleString()}`, { align: 'left' });
    doc.moveDown(0.5);
    doc.fontSize(11).fillColor('#f8fafc').text(`Total Income: ${formatCurrency(summary.totalIncome)}`);
    doc.text(`Total Expense: ${formatCurrency(summary.totalExpense)}`);
    doc.text(`Net Balance: ${formatCurrency(summary.netBalance)}`);
    doc.moveDown(0.75);

    doc.fontSize(12).fillColor('#cbd5e1');
    const tableTop = doc.y;
    const itemHeaders = ['Date', 'Title', 'Category', 'Type', 'Amount', 'Payment', 'Notes'];
    const columnWidths = [70, 110, 90, 60, 70, 80, 90];
    itemHeaders.forEach((header, index) => doc.text(header, { continued: index !== itemHeaders.length - 1, width: columnWidths[index], align: 'left' }));
    doc.moveDown(0.5);

    transactions.forEach((transaction) => {
      doc.fontSize(10).fillColor('#e2e8f0');
      const values = [
        transaction.date.toISOString().split('T')[0],
        transaction.title,
        transaction.category?.name || 'Uncategorized',
        transaction.type,
        formatCurrency(transaction.amount),
        transaction.paymentMethod || 'Unknown',
        transaction.note || '',
      ];
      values.forEach((value, index) => doc.text(value, { continued: index !== values.length - 1, width: columnWidths[index], align: 'left' }));
      doc.moveDown(0.5);
    });

    doc.end();
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};

export const exportExcelReport = async (req, res) => {
  try {
    const query = buildQuery(req.query, req.user._id);
    const transactions = await populateTransactions(query);
    const summary = buildSummary(transactions);
    const reportMeta = buildReportMeta(req.user.name, req.query.title || 'Expense Report');

    const workbook = new ExcelJS.Workbook();
    const sheet = workbook.addWorksheet('Report');

    sheet.columns = [
      { header: 'Date', key: 'date', width: 15 },
      { header: 'Title', key: 'title', width: 30 },
      { header: 'Description', key: 'description', width: 30 },
      { header: 'Category', key: 'category', width: 20 },
      { header: 'Type', key: 'type', width: 12 },
      { header: 'Amount', key: 'amount', width: 15 },
      { header: 'Payment Method', key: 'paymentMethod', width: 18 },
      { header: 'Notes', key: 'notes', width: 30 },
    ];

    sheet.addRow([reportMeta.reportTitle]);
    sheet.addRow([`Generated by: ${reportMeta.generatedBy}`]);
    sheet.addRow([`Generated at: ${new Date(reportMeta.generatedAt).toLocaleString()}`]);
    sheet.addRow([]);
    sheet.addRow(['Total Income', formatCurrency(summary.totalIncome)]);
    sheet.addRow(['Total Expense', formatCurrency(summary.totalExpense)]);
    sheet.addRow(['Net Balance', formatCurrency(summary.netBalance)]);
    sheet.addRow([]);
    sheet.addRow();

    transactions.forEach((transaction) => {
      sheet.addRow({
        date: transaction.date.toISOString().split('T')[0],
        title: transaction.title,
        description: transaction.note || '',
        category: transaction.category?.name || 'Uncategorized',
        type: transaction.type,
        amount: transaction.amount,
        paymentMethod: transaction.paymentMethod || 'Unknown',
        notes: transaction.note || '',
      });
    });

    res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
    res.setHeader('Content-Disposition', getAttachmentFilenameHeader(reportMeta, 'xlsx'));

    await workbook.xlsx.write(res);
    res.end();
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};

export const exportCsvReport = async (req, res) => {
  try {
    const query = buildQuery(req.query, req.user._id);
    const transactions = await populateTransactions(query);
    const reportMeta = buildReportMeta(req.user.name, req.query.title || 'Expense Report');

    const rows = buildRows(transactions);
    const parser = new Parser({ fields: ['date', 'title', 'description', 'category', 'type', 'amount', 'paymentMethod', 'notes'] });
    const csv = parser.parse(rows);

    const headerRows = [
      ['Report Title', reportMeta.reportTitle],
      ['Generated By', reportMeta.generatedBy],
      ['Generated At', new Date(reportMeta.generatedAt).toLocaleString()],
      [],
    ];
    const csvHeader = headerRows.map((row) => row.join(',')).join('\n');
    const csvWithHeader = `${csvHeader}\n${csv}`;

    res.setHeader('Content-Type', 'text/csv');
    res.setHeader('Content-Disposition', getAttachmentFilenameHeader(reportMeta, 'csv'));
    res.send(csvWithHeader);
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};